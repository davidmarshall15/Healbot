local function read(path)
    local f=assert(io.open(path,'rb')); local s=f:read('*a'); f:close()
    return s:gsub('\r\n','\n'):gsub('^\239\187\191','')
end
local prefix=assert(read('tests/native_buff_casters.lua'):match('^(.-)\nlocal function admits%('))
local fixture=assert(loadstring(prefix..'\nreturn fixture'))()
local d=fixture('PRIEST',4)
local b=d.button(); local row=assert(d.row(b))
local zone='none'
d.env.IsInInstance=function() return zone~='none',zone end
local allocated=#d.frames
assert(not row.shown and b.gref.icon[1].shown,'world legacy renderer changed')
zone='pvp'; d.hook('HealBot_Aura_SetAuraCheckFlags')
assert(row.shown and not b.gref.icon[1].shown,'BG outside combat did not take over native buffs')
d.fire('PLAYER_ENTERING_WORLD')
assert(row.groups.hbcahot.options.candidateFilters.includeSpellIDs[139],'Renew missing from native group')
assert(row.groups.hbcahot.options.candidateFilters.includeSpellIDs[17],'Shield missing from native group')
d.combat(true); assert(row.shown,'entering combat hid native BG icons')
d.combat(false); assert(row.shown,'leaving combat hid native BG icons')
d.config.BuffWatch=false; d.hook('HealBot_Aura_SetAuraCheckFlags')
assert(not row.shown,'BG renderer ignored Monitor buffs')
d.config.BuffWatch=true; d.hook('HealBot_Aura_SetAuraCheckFlags')
assert(row.shown,'BG renderer did not restore enabled buff monitor')
d.config.BuffCustomWatchInCombat=false; d.combat(true)
assert(not row.shown,'BG renderer ignored Also in combat')
d.combat(false); assert(row.shown,'BG outside combat incorrectly requires Also in combat')
zone='none'; d.fire('PLAYER_ENTERING_WORLD')
assert(not row.shown and b.gref.icon[1].shown,'leaving BG did not restore legacy ownership')
zone='party'; d.fire('PLAYER_ENTERING_WORLD'); assert(not row.shown,'dungeon behavior changed')
zone='raid'; d.fire('PLAYER_ENTERING_WORLD'); assert(not row.shown,'raid instance behavior changed')
zone='arena'; d.fire('PLAYER_ENTERING_WORLD'); assert(row.shown,'arena outside-combat gap remains')
d.env.UnitIsConnected=function() return false end
d.hook('HealBot_Aura_SetAuraCheckFlags'); assert(not row.shown,'disconnected unit retained native icons')
d.env.UnitIsConnected=function() return true end
d.hook('HealBot_Aura_SetAuraCheckFlags'); assert(row.shown,'reconnected unit did not recover')
b.status.events=false; d.hook('HealBot_Action_UnregisterUnitEvents',b)
d.fire('PLAYER_ENTERING_WORLD'); assert(not row.shown,'zone refresh revived an unregistered bar')
assert(#d.frames==allocated,'BG transitions allocated native frames')
print('PASS: BG and arena native buff handoff, Renew/Shield policy, combat transitions, settings, dungeon/raid/world behavior; no new frames')
